'use client';

import { Document, Page, StyleSheet, Text, View } from '@react-pdf/renderer';

import { number } from '@/lib/format';
import {
  riskBand,
  totalFindings,
  SEVERITY_LABEL,
  type ReportRow,
  type Severity,
} from '@/lib/types';

const SEVERITY_HEX: Record<Severity, string> = {
  critical: '#b91c1c',
  high: '#c2570a',
  medium: '#a16207',
  low: '#0e7490',
  info: '#475569',
};

const styles = StyleSheet.create({
  page: { padding: 40, fontSize: 9, fontFamily: 'Helvetica', color: '#111827' },
  header: {
    marginBottom: 20,
    paddingBottom: 14,
    borderBottomWidth: 1,
    borderBottomColor: '#e5e7eb',
  },
  brand: { fontSize: 8, letterSpacing: 2, color: '#2563eb', marginBottom: 6 },
  title: { fontSize: 20, fontFamily: 'Helvetica-Bold', marginBottom: 4 },
  meta: { fontSize: 8, color: '#6b7280' },
  kpiRow: { flexDirection: 'row', justifyContent: 'space-between', marginBottom: 20 },
  kpi: { borderWidth: 1, borderColor: '#e5e7eb', borderRadius: 4, padding: 10, width: '24%' },
  kpiLabel: { fontSize: 7, color: '#6b7280', marginBottom: 3 },
  kpiValue: { fontSize: 15, fontFamily: 'Helvetica-Bold' },
  h2: {
    fontSize: 11,
    fontFamily: 'Helvetica-Bold',
    marginTop: 16,
    marginBottom: 6,
    paddingBottom: 3,
    borderBottomWidth: 1,
    borderBottomColor: '#e5e7eb',
  },
  p: { fontSize: 9, lineHeight: 1.6, marginBottom: 8 },
  bullet: { fontSize: 9, lineHeight: 1.55, marginBottom: 4, paddingLeft: 10 },
  tableHeader: {
    flexDirection: 'row',
    backgroundColor: '#f3f4f6',
    paddingVertical: 5,
    paddingHorizontal: 6,
    borderRadius: 2,
    marginBottom: 2,
  },
  th: { fontSize: 7, fontFamily: 'Helvetica-Bold', color: '#4b5563' },
  row: {
    flexDirection: 'row',
    paddingVertical: 5,
    paddingHorizontal: 6,
    borderBottomWidth: 0.5,
    borderBottomColor: '#f3f4f6',
  },
  colIssue: { width: '42%' },
  colSev: { width: '16%' },
  colCvss: { width: '12%' },
  colHosts: { width: '14%' },
  sev: { fontFamily: 'Helvetica-Bold', fontSize: 8 },
  footer: {
    position: 'absolute',
    bottom: 24,
    left: 40,
    right: 40,
    flexDirection: 'row',
    justifyContent: 'space-between',
    fontSize: 7,
    color: '#9ca3af',
  },
});

export function ReportPdfDocument({ report }: { report: ReportRow }) {
  const ai = report.ai_report;
  const band = riskBand(report.risk_score);
  const findings = totalFindings(report.severity_counts);
  const top = [...report.findings]
    .sort((a, b) => {
      const order: Severity[] = ['critical', 'high', 'medium', 'low', 'info'];
      return order.indexOf(a.severity) - order.indexOf(b.severity) || b.occurrences - a.occurrences;
    })
    .slice(0, 25);

  return (
    <Document
      title={`${report.title} — Aegis VAPT Report`}
      author="Aegis Compliance Portal"
      subject="Vulnerability assessment report"
      keywords="vapt, security, compliance"
      creator="Aegis"
      producer="Aegis"
      language="en"
    >
      <Page size="A4" style={styles.page}>
        <View style={styles.footer} fixed>
          <Text>Confidential — generated by Aegis</Text>
          <Text render={({ pageNumber, totalPages }) => `${pageNumber} / ${totalPages}`} />
        </View>

        <View style={styles.header} fixed>
          <Text style={styles.brand}>AEGIS COMPLIANCE PORTAL</Text>
          <Text style={styles.title}>{report.title}</Text>
          <Text style={styles.meta}>
            {ai
              ? `Generated ${new Date(ai.generatedAt).toLocaleString('en-GB')} · model ${ai.model}`
              : 'Draft'}
          </Text>
        </View>

        <View style={styles.kpiRow}>
          <View style={styles.kpi}>
            <Text style={styles.kpiLabel}>Risk score</Text>
            <Text
              style={[
                styles.kpiValue,
                { color: band.tone === 'low' ? '#15803d' : SEVERITY_HEX[band.tone] },
              ]}
            >
              {report.risk_score ?? '—'}
            </Text>
            <Text style={styles.kpiLabel}>{band.label}</Text>
          </View>
          <View style={styles.kpi}>
            <Text style={styles.kpiLabel}>Findings</Text>
            <Text style={styles.kpiValue}>{number(findings)}</Text>
          </View>
          <View style={styles.kpi}>
            <Text style={styles.kpiLabel}>Assets</Text>
            <Text style={styles.kpiValue}>{number(report.asset_count)}</Text>
          </View>
          <View style={styles.kpi}>
            <Text style={styles.kpiLabel}>Critical</Text>
            <Text
              style={[
                styles.kpiValue,
                { color: report.severity_counts.critical > 0 ? SEVERITY_HEX.critical : '#15803d' },
              ]}
            >
              {number(report.severity_counts.critical)}
            </Text>
          </View>
        </View>

        {ai && (
          <>
            <Text style={styles.h2}>Executive summary</Text>
            <Text style={styles.p}>{ai.executiveSummary}</Text>

            <Text style={styles.h2}>Business risk</Text>
            <Text style={styles.p}>{ai.businessRisk}</Text>

            <Text style={styles.h2}>Compliance posture</Text>
            <Text style={styles.p}>{ai.compliancePosture}</Text>

            {ai.keyTakeaways.length > 0 && (
              <>
                <Text style={styles.h2}>Key takeaways</Text>
                {ai.keyTakeaways.map((item, index) => (
                  <Text key={index} style={styles.bullet}>
                    • {item}
                  </Text>
                ))}
              </>
            )}

            {ai.remediationPlan.length > 0 && (
              <>
                <Text style={styles.h2}>Remediation plan</Text>
                {ai.remediationPlan.map((item, index) => (
                  <View key={index} style={{ marginBottom: 8 }}>
                    <Text style={{ fontFamily: 'Helvetica-Bold', fontSize: 9 }}>
                      {index + 1}. {item.title}
                    </Text>
                    <Text style={{ fontSize: 8, color: '#374151', lineHeight: 1.5 }}>
                      {item.detail}
                    </Text>
                    <Text style={{ fontSize: 7, color: '#6b7280', marginTop: 2 }}>
                      Severity {SEVERITY_LABEL[item.severity]} · {item.effort} effort ·{' '}
                      {item.window}
                    </Text>
                  </View>
                ))}
              </>
            )}
          </>
        )}

        {top.length > 0 && (
          <>
            <Text style={styles.h2}>Top findings (sanitised)</Text>
            <View style={styles.tableHeader}>
              <Text style={[styles.th, styles.colIssue]}>Issue</Text>
              <Text style={[styles.th, styles.colSev]}>Severity</Text>
              <Text style={[styles.th, styles.colCvss]}>CVSS</Text>
              <Text style={[styles.th, styles.colHosts]}>Hosts</Text>
            </View>
            {top.map((finding) => (
              <View key={finding.id} style={styles.row} wrap={false}>
                <View style={styles.colIssue}>
                  <Text style={{ fontSize: 8 }}>{finding.title}</Text>
                  {finding.affected ? (
                    <Text style={{ fontSize: 7, color: '#6b7280' }}>{finding.affected}</Text>
                  ) : null}
                </View>
                <Text
                  style={[styles.colSev, styles.sev, { color: SEVERITY_HEX[finding.severity] }]}
                >
                  {SEVERITY_LABEL[finding.severity]}
                </Text>
                <Text style={styles.colCvss}>
                  {finding.cvss === null ? '—' : finding.cvss.toFixed(1)}
                </Text>
                <Text style={styles.colHosts}>{number(finding.occurrences)}</Text>
              </View>
            ))}
          </>
        )}
      </Page>
    </Document>
  );
}

